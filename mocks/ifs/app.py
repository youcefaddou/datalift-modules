SEED: dict[tuple[str, str], list[dict[str, Any]]] = {
    tuple(name.split("/")): rows
    for name, rows in json.loads((Path(__file__).parent / "seed.json").read_text()).items()
}

RESOURCE = re.compile(r"^(?P<set>\w+)(?:\((?P<keys>[^)]*)\))?(?:/(?P<nav>\w+))?$")
KEY_PART = re.compile(r"(?P<field>\w+)=(?:'(?P<text>[^']*)'|(?P<num>-?\d+))")
FILTER_PART = re.compile(
    r"^(?P<field>\w+) eq (?:(?P<enum>IfsApp\.[\w.]+)?'(?P<text>[^']*)'"
    r"|(?P<num>-?\d+(?:\.\d+)?|true|false))$"
)


def _text(value: Any) -> str:
    return json.dumps(value) if isinstance(value, bool) else str(value)


def _snake(name: str) -> str:
    """CustomerId -> CUSTOMER_ID, as in IFS keyref."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def _prompt(lu: str) -> str:
    """CustomerInfo -> Customer Info, as in IFS error messages."""
    return re.sub(r"(?<!^)(?=[A-Z])", " ", lu)


def _etag(row: dict[str, Any]) -> str:
    digest = hashlib.sha1(json.dumps(row, sort_keys=True, default=str).encode()).digest()
    return f'W/"{base64.b64encode(digest).decode()}"'


def _odata_error(
    status: int, code: str, message: str, details: list | None = None
) -> HTTPException:
    error: dict[str, Any] = {"code": code, "message": message}
    if details:
        error["details"] = details
    return HTTPException(status, error)


def _database_error(ora: int, text: str) -> HTTPException:
    detail = {"code": ora, "message": f"ORA-{ora}: {text}"}
    return _odata_error(
        500, "DATABASE_ERROR", "Database error occurred. Contact administrator.", [detail]
    )


def _parse_filter(expression: str, enums: dict[str, tuple]) -> list[tuple[str, str]]:
    # ponytail: only `Field eq value` joined by `and`; add operators when a connector needs them.
    clauses = []
    for part in expression.split(" and "):
        match = FILTER_PART.match(part.strip())
        if not match:
            raise _odata_error(400, "ODP_BAD_REQUEST", f"Unsupported $filter clause: {part}")
        field = match["field"]
        if field in enums and match["enum"] != enums[field][0]:
            raise _odata_error(
                400, "ODP_BAD_REQUEST", f"{field} is an enumeration: use {enums[field][0]}'Value'"
            )
        clauses.append((field, match["text"] if match["text"] is not None else match["num"]))
    return clauses


def create_app() -> FastAPI:
    store = copy.deepcopy(SEED)
    tokens: dict[str, float] = {}
    app = FastAPI(title="IFS Cloud mock (reconstructed)")

    def authorize(authorization: str | None) -> None:
        scheme, _, value = (authorization or "").partition(" ")
        if scheme.lower() != "bearer" or tokens.get(value, 0) < time.time():
            raise _odata_error(401, "UNAUTHORIZED", "Missing or expired access token")

    def conf(target: tuple[str, str], name: str) -> Any:
        return ENTITY_SETS[target].get(name, {} if name in ("enums", "defaults") else [])

    def resolve(projection: str, resource: str) -> tuple[tuple[str, str], dict | None, str | None]:
        match = RESOURCE.match(resource)
        target = (projection, match["set"]) if match else None
        if target not in ENTITY_SETS:
            raise _odata_error(
                404, "ODP_RESOURCE_NOTFOUND", f"Unknown entity set: {projection}.svc/{resource}"
            )
        nav = match["nav"]
        if nav is not None and (match["keys"] is None or nav not in conf(target, "navs")):
            raise _odata_error(404, "ODP_RESOURCE_NOTFOUND", f"Unknown navigation: {resource}")
        if match["keys"] is None:
            return target, None, None
        keys = {
            m["field"]: m["text"] if m["text"] is not None else m["num"]
            for m in KEY_PART.finditer(match["keys"])
        }
        if set(keys) != set(conf(target, "keys")):
            raise _odata_error(400, "ODP_BAD_REQUEST", f"Expected keys {conf(target, 'keys')}")
        return target, keys, nav

    def find(target: tuple[str, str], keys: dict[str, str]) -> dict[str, Any] | None:
        return next(
            (r for r in store[target] if all(_text(r.get(k)) == v for k, v in keys.items())), None
        )

    def found(target: tuple[str, str], keys: dict[str, str]) -> dict[str, Any]:
        row = find(target, keys)
        if row is None:
            raise _odata_error(404, "ODP_RESOURCE_NOTFOUND", "Entity not found")
        return row

    def entity(target: tuple[str, str], row: dict[str, Any]) -> dict[str, Any]:
        """Row as IFS returns it: etag, luname, keyref and Objgrants before the fields."""
        fields = {k: v for k, v in row.items() if k not in conf(target, "navs")}
        keyref = "".join(f"{_snake(k)}={row.get(k)}^" for k in conf(target, "keys"))
        meta = {
            "@odata.etag": _etag(fields),
            "luname": conf(target, "lu"),
            "keyref": keyref,
            "Objgrants": None,
        }
        return {**meta, **fields}

    def check_enums(target: tuple[str, str], payload: dict[str, Any]) -> None:
        for field, (_, allowed) in conf(target, "enums").items():
            if allowed and field in payload and payload[field] not in allowed:
                raise _odata_error(
                    400, "ODP_BAD_REQUEST", f"Invalid value for {field}: {payload[field]}"
                )

    def page(
        rows: list[dict[str, Any]], request: Request, context: str, enums: dict
    ) -> dict[str, Any]:
        params = request.query_params
        if "$expand" in params:
            raise _odata_error(400, "ODP_NOT_IMPLEMENTED", "$expand is not implemented")
        if "$filter" in params:
            clauses = _parse_filter(params["$filter"], enums)
            rows = [r for r in rows if all(_text(r.get(f)) == v for f, v in clauses)]
        for term in reversed(params.get("$orderby", "").split(",")):
            if term.strip():
                field, _, direction = term.strip().partition(" ")
                rows = sorted(
                    rows, key=lambda r, f=field: _text(r.get(f)), reverse=direction == "desc"
                )
        top = int(params.get("$top", DEFAULT_PAGE_SIZE))
        skip = int(params.get("$skip", 0))
        values = rows[skip : skip + top]
        if "$select" in params:
            fields = [f.strip() for f in params["$select"].split(",")]
            values = [{f: r.get(f) for f in fields} for r in values]
        body: dict[str, Any] = {"@odata.context": context, "value": values}
        if skip + top < len(rows):
            query = {**params, "$top": top, "$skip": skip + top}
            body["@odata.nextLink"] = f"{request.url.path}?{urlencode(query, safe="$',")}"
        return body

    @app.get(f"/auth/realms/{REALM}/.well-known/openid-configuration")
    def openid_configuration(request: Request) -> dict[str, Any]:
        issuer = f"{str(request.base_url).rstrip('/')}/auth/realms/{REALM}"
        return {
            "issuer": issuer,
            "token_endpoint": f"{issuer}/protocol/openid-connect/token",
            "grant_types_supported": ["client_credentials"],
        }

    @app.post(TOKEN_PATH)
    async def issue_token(request: Request) -> dict[str, Any]:
        form = {k: v[0] for k, v in parse_qs((await request.body()).decode()).items()}
        if form.get("grant_type") != "client_credentials":
            raise HTTPException(400, {"error": "unsupported_grant_type"})
        if (form.get("client_id"), form.get("client_secret")) != (CLIENT_ID, CLIENT_SECRET):
            raise HTTPException(401, {"error": "invalid_client"})
        access_token = secrets.token_urlsafe(32)
        tokens[access_token] = time.time() + TOKEN_TTL_SECONDS
        return {
            "access_token": access_token,
            "token_type": "Bearer",
            "expires_in": TOKEN_TTL_SECONDS,
        }

    @app.get(PREFIX + "/{projection}.svc/{resource:path}")
    def read(
        projection: str,
        resource: str,
        request: Request,
        authorization: Annotated[str | None, Header()] = None,
    ) -> dict[str, Any]:
        authorize(authorization)
        context = f"{PREFIX}/{projection}.svc/$metadata"
        if resource == "":
            sets = [s for p, s in ENTITY_SETS if p == projection]
            if not sets:
                raise _odata_error(
                    404, "ODP_RESOURCE_NOTFOUND", f"Unknown projection: {projection}"
                )
            return {
                "@odata.context": context,
                "value": [{"name": s, "kind": "EntitySet", "url": s} for s in sets],
            }
        target, keys, nav = resolve(projection, resource)
        if keys is None:
            rows = [entity(target, r) for r in store[target]]
            return page(rows, request, f"{context}#{target[1]}", conf(target, "enums"))
        row = found(target, keys)
        if nav is None:
            return {"@odata.context": f"{context}#{target[1]}/$entity", **entity(target, row)}
        return page(row[nav], request, f"{context}#{resource}", {})

    @app.post(PREFIX + "/{projection}.svc/{resource:path}", status_code=201)
    def create(
        projection: str,
        resource: str,
        payload: dict[str, Any],
        authorization: Annotated[str | None, Header()] = None,
    ) -> dict[str, Any]:
        authorize(authorization)
        target, keys, nav = resolve(projection, resource)
        if nav is not None:
            found(target, keys)[nav].append(payload)
            return payload
        if keys is not None:
            raise _odata_error(405, "ODP_NOT_ALLOWED", "POST on a collection or a navigation only")
        check_enums(target, payload)
        lu = conf(target, "lu")
        for field in conf(target, "required"):
            if payload.get(field) in (None, ""):
                raise _database_error(
                    20124,
                    f"Error.NULLVALUE: Field [{field}] is mandatory for {_prompt(lu)} and requires a value.",
                )
        row = {**conf(target, "defaults"), **payload}
        autokey = ENTITY_SETS[target].get("autokey")
        if autokey and row.get(autokey) in (None, ""):
            numbers = [int(v) for r in store[target] if str(v := r.get(autokey)).isdigit()]
            value = max(numbers, default=0) + 1
            row[autokey] = (
                value if any(isinstance(r.get(autokey), int) for r in store[target]) else str(value)
            )
        if find(target, {k: _text(row.get(k)) for k in conf(target, "keys")}):
            # ponytail: ORA number reconstructed; only "already exists" is confirmed (video V1).
            raise _database_error(20112, f"{lu}.EXIST: The {_prompt(lu)} already exists.")
        store[target].append({**row, **{n: [] for n in conf(target, "navs")}})
        return {
            "@odata.context": f"{PREFIX}/{projection}.svc/$metadata#{target[1]}/$entity",
            **entity(target, row),
        }

    @app.patch(PREFIX + "/{projection}.svc/{resource:path}")
    def update(
        projection: str,
        resource: str,
        payload: dict[str, Any],
        authorization: Annotated[str | None, Header()] = None,
        if_match: Annotated[str | None, Header()] = None,
    ) -> dict[str, Any]:
        authorize(authorization)
        target, keys, nav = resolve(projection, resource)
        if keys is None or nav is not None:
            raise _odata_error(405, "ODP_NOT_ALLOWED", "PATCH on a single entity only")
        row = found(target, keys)
        if if_match is None:
            raise _odata_error(428, "ODP_MISSING_PRECONDITION", "If-Match header is required")
        if if_match != "*" and if_match != entity(target, row)["@odata.etag"]:
            raise _odata_error(
                412, "ODP_PRECONDITION_FAILED", "The entity was modified since it was read"
            )
        check_enums(target, payload)
        navs = conf(target, "navs")
        row.update({k: v for k, v in payload.items() if k not in keys and k not in navs})
        return entity(target, row)

    @app.exception_handler(RequestValidationError)
    def deserialization_error(_: Request, __: RequestValidationError) -> JSONResponse:
        error = {
            "code": "ODP_DESERIALIZATION_ERROR",
            "message": "Error while de-serializing contents.",
        }
        return JSONResponse({"error": error}, status_code=400)

    @app.exception_handler(HTTPException)
    def odata_error(_: Request, exc: HTTPException) -> JSONResponse:
        detail = (
            exc.detail
            if isinstance(exc.detail, dict)
            else {"code": str(exc.status_code), "message": exc.detail}
        )
        body = detail if "error" in detail else {"error": detail}
        return JSONResponse(body, status_code=exc.status_code)

    return app


app = create_app()
